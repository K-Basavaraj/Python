#A list of EC2 instance Ids 
isinstances = ["i-0abc123", "i-0abc124", "i-0abc125"]

#Positive Indexing Index starts from 0 Positive indexing  → Left to Right
print(isinstances[0]) 
print(isinstances[1])
print(isinstances[2])
"""
output: 
i-0abc123
i-0abc124
i-0abc125
"""
#Negative Indexing Negative indexing starts from the end. Negative indexing  → Right to Left
print(isinstances[-1])
print(isinstances[-2])
print(isinstances[-3])
"""
output: 
i-0abc125
i-0abc124
i-0abc123
"""

