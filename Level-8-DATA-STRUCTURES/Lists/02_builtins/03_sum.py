"""
Sum Function in Python

Purpose:
Helps calculate the total of all numeric values in a list.

Real-world example:
Useful for calculating total expenses, total marks,
total sales, or total quantities.

Practical application:
Avoids manually adding each value one by one.

The sum() function returns the total of all numbers in the list.
"""
#example1: 
marks = [85, 92, 78, 96, 88]

total_marks = sum(marks)

print(total_marks)
# output: 439
# sum() adds all numbers in the list.

#example2: 
expenses = [500, 1200, 300, 750]

print(sum(expenses))
# output: 2750
# sum() calculates the total expenses.